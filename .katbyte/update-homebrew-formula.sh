#!/usr/bin/env bash
#
# Regenerates the source-build formula in katbyte/homebrew-tap for a released tag.
# Usage: TAG=v0.15.0-kt.1 [TAP_DRY_RUN=1] HOMEBREW_TAP_GITHUB_TOKEN=... ./.katbyte/update-homebrew-formula.sh
set -euo pipefail

TAG="${TAG:?set TAG to the release tag, e.g. v0.15.0-kt.1}"
VERSION="${TAG#v}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "==> fetching source tarball for ${TAG}..."
curl -sSfL "https://github.com/katbyte/smartctl_exporter/archive/refs/tags/${TAG}.tar.gz" -o "$tmp/src.tar.gz"

# GitHub answers some missing tarballs with a web page rather than an error, and its hash would make a formula that never installs
tar -tzf "$tmp/src.tar.gz" > /dev/null 2>&1 || { echo "==> ${TAG} has no source tarball on GitHub yet" >&2; exit 1; }
SHA256="$(sha256sum "$tmp/src.tar.gz" | cut -d' ' -f1)"

cat > "$tmp/smartctl_exporter.rb" <<FORMULA
# typed: false
# frozen_string_literal: true

# This file is generated by the smartctl_exporter release workflow - do not edit by hand.
class SmartctlExporter < Formula
  desc "Disk health from smartctl for Prometheus, katbyte's build of smartctl_exporter"
  homepage "https://github.com/katbyte/smartctl_exporter"
  url "https://github.com/katbyte/smartctl_exporter/archive/refs/tags/${TAG}.tar.gz"
  # set outright rather than left for Homebrew to guess from the tarball's name
  version "${VERSION}"
  sha256 "${SHA256}"
  license "Apache-2.0"
  head "https://github.com/katbyte/smartctl_exporter.git", branch: "master"

  depends_on "go" => :build
  depends_on "smartmontools"

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/prometheus/common/version.Version=${VERSION} -X github.com/prometheus/common/version.Revision=homebrew -X github.com/prometheus/common/version.Branch=master -X github.com/prometheus/common/version.BuildUser=homebrew")
  end

  # brew services start smartctl_exporter keeps it running. smartctl comes from the smartmontools formula, not /usr/sbin where the exporter looks by default
  service do
    run [opt_bin/"smartctl_exporter", "--smartctl.path=#{Formula["smartmontools"].opt_bin}/smartctl"]
    keep_alive true
    log_path var/"log/smartctl_exporter.log"
    error_log_path var/"log/smartctl_exporter.log"
  end

  test do
    assert_match "${VERSION}", shell_output("#{bin}/smartctl_exporter --version 2>&1")
  end
end
FORMULA

if [ "${TAP_DRY_RUN:-0}" = "1" ]; then
  echo "==> dry run; generated formula:"
  cat "$tmp/smartctl_exporter.rb"
  exit 0
fi

: "${HOMEBREW_TAP_GITHUB_TOKEN:?set HOMEBREW_TAP_GITHUB_TOKEN to a token with push access to katbyte/homebrew-tap}"
echo "==> pushing formula to katbyte/homebrew-tap..."
git clone --depth 1 "https://x-access-token:${HOMEBREW_TAP_GITHUB_TOKEN}@github.com/katbyte/homebrew-tap.git" "$tmp/tap"
mkdir -p "$tmp/tap/Formula"
cp "$tmp/smartctl_exporter.rb" "$tmp/tap/Formula/smartctl_exporter.rb"
cd "$tmp/tap"
git config user.name "smartctl_exporter-release"
git config user.email "smartctl_exporter-release@katbyte.me"
git add Formula/smartctl_exporter.rb
git diff --cached --quiet && { echo "==> formula unchanged"; exit 0; }
git commit -m "smartctl_exporter ${TAG}"
git push
echo "==> done"
